"use client";

import { startTransition, useActionState, useEffect, useState } from "react";
import { useRouter } from "next/navigation";
import { registerStudent, type RegisterStudentFormState } from "@/lib/academies/register-student-actions";
import { showInfoToast, showSuccessToast } from "@/lib/ui/toast";
import { PaymentPlanField } from "@/app/academy/_shell/payment-plan-field";
import type { EnrollBatchOption } from "@/lib/academies/enroll-options";
import { StudentPhotoField } from "./student-photo-field";
import {
  DField,
  DesignDialog,
  useUrlOpenedDialog,
  DialogBody,
  DialogFooter,
  FieldGrid,
  FormErrorBanner,
  PhoneField,
  controlClass,
  invalidProps,
  onDesignSubmit,
  useDesignForm,
  type DesignFormRule,
} from "@/app/academy/_shell/design-form";

/**
 * Register student (design A02 form `student`): Full name, Branch, Phone,
 * Email, Guardian name, Guardian phone, Date of birth, Gender, Student
 * photo — in that order, on the design's form system. Two reconciliations
 * with the real data model, both deliberate:
 * - The design's "Home address" and "City / district" are omitted: the
 *   students table has no such columns, and adding them would be a schema
 *   change made only for the visual.
 * - The application's existing optional "enroll now" step (course + payment
 *   plan, submitted with the registration) is kept as a clearly optional
 *   last section; the design enrolls separately, which also still works
 *   (Admissions / Enroll).
 *
 * The student number is generated by the server; `registerStudent` does all
 * authoritative validation, scoping and audit logging.
 */


const initialState: RegisterStudentFormState = { ok: false };

const SERVER_FIELD_PATTERNS: [RegExp, string][] = [
  [/email/i, "email"],
  [/date of birth|born/i, "dateOfBirth"],
  [/full name/i, "fullName"],
  [/branch/i, "branchId"],
  [/guardian phone/i, "guardianPhone"],
  [/phone/i, "phone"],
  [/fee|amount/i, "paymentPlanAmountDollars"],
  [/address/i, "address"],
  [/district/i, "district"],
  [/course/i, "courseIds"],
];

function todayIso() {
  const now = new Date();
  return `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, "0")}-${String(now.getDate()).padStart(2, "0")}`;
}

const RULES: DesignFormRule[] = [
  { name: "fullName", label: "Full name", required: true },
  {
    name: "address",
    label: "Home address",
    check: (value) => (value.trim().length > 500 ? "Keep the address under 500 characters." : null),
  },
  {
    name: "district",
    label: "District",
    check: (value) => (value.trim().length > 120 ? "Keep the district under 120 characters." : null),
  },
  { name: "branchId", label: "Branch", required: true, kind: "select" },
  {
    name: "email",
    label: "Email",
    check: (value) => (value.trim() && !/^\S+@\S+\.\S+$/.test(value.trim()) ? "Enter a valid email address." : null),
  },
  {
    name: "dateOfBirth",
    label: "Date of birth",
    check: (value) => (value && value > todayIso() ? "Date of birth cannot be in the future." : null),
  },
  {
    name: "courseIds",
    label: "Courses",
    check: (_value, data) =>
      String(data.get("batchId") ?? "") && data.getAll("courseIds").length === 0 ? "Pick at least one course." : null,
  },
  {
    name: "paymentPlanAmountDollars",
    label: "Total fee",
    check: (value, data) => {
      if (!String(data.get("batchId") ?? "")) return null;
      if (!value.trim()) return "Total fee is required when enrolling now.";
      return /^\d+(\.\d{1,2})?$/.test(value.trim()) && Number(value) > 0 ? null : "Enter an amount like 180 or 180.50.";
    },
  },
];

export interface RegisterStudentOptions {
  branches: { id: string; name: string }[];
  /** Planned and active batches with their courses (empty: no enroll step). */
  enrollBatches: EnrollBatchOption[];
}

function RegisterStudentFields({
  branches,
  enrollBatches,
  onCancel,
}: RegisterStudentOptions & { onCancel: () => void }) {
  const router = useRouter();
  const [state, formAction, pending] = useActionState(registerStudent, initialState);
  const { formRef, errors, banner, validate, blur, showServerError } = useDesignForm(RULES);
  const [batchId, setBatchId] = useState("");
  const [courseIds, setCourseIds] = useState<string[]>([]);
  const enrollBatch = enrollBatches.find((batch) => batch.id === batchId) ?? null;

  useEffect(() => {
    if (state.ok && state.studentId) {
      if (state.enrollmentWarning) showInfoToast(state.enrollmentWarning);
      else showSuccessToast("Student registered.");
      router.push(`/academy/students/${state.studentId}`);
    } else if (!state.ok && state.error) {
      showServerError(state.error.message, SERVER_FIELD_PATTERNS);
    }
    // showServerError is stable (useCallback); re-run only on a new result.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [state, router]);

  return (
    <form
      ref={formRef}
      noValidate
      className="flex min-h-0 flex-1 flex-col"
      onSubmit={onDesignSubmit(validate, (data) => startTransition(() => formAction(data)))}
    >
      <DialogBody>
        <FieldGrid>
          <DField label="Full name" name="fullName" required error={errors.fullName} full>
            <input
              type="text"
              name="fullName"
              autoComplete="name"
              onBlur={blur("fullName")}
              className={controlClass(Boolean(errors.fullName))}
              {...invalidProps("fullName", errors.fullName)}
            />
          </DField>
          <DField label="Branch" name="branchId" required error={errors.branchId}>
            <select
              name="branchId"
              defaultValue={branches.length === 1 ? branches[0].id : ""}
              onBlur={blur("branchId")}
              className={controlClass(Boolean(errors.branchId))}
              {...invalidProps("branchId", errors.branchId)}
            >
              <option value="">Select a branch</option>
              {branches.map((branch) => (
                <option key={branch.id} value={branch.id}>
                  {branch.name}
                </option>
              ))}
            </select>
          </DField>
          <DField label="Phone" name="phone" error={errors.phone}>
            <PhoneField name="phone" error={errors.phone} />
          </DField>
          <DField label="Email (optional)" name="email" error={errors.email}>
            <input
              type="email"
              name="email"
              autoComplete="email"
              onBlur={blur("email")}
              className={controlClass(Boolean(errors.email))}
              {...invalidProps("email", errors.email)}
            />
          </DField>
          <DField label="Guardian name" name="guardianName" error={errors.guardianName}>
            <input type="text" name="guardianName" className={controlClass(false)} />
          </DField>
          <DField label="Guardian phone" name="guardianPhone" error={errors.guardianPhone}>
            <PhoneField name="guardianPhone" error={errors.guardianPhone} />
          </DField>
          <DField label="Date of birth" name="dateOfBirth" error={errors.dateOfBirth}>
            <input
              type="date"
              name="dateOfBirth"
              max={todayIso()}
              onBlur={blur("dateOfBirth")}
              className={controlClass(Boolean(errors.dateOfBirth))}
              {...invalidProps("dateOfBirth", errors.dateOfBirth)}
            />
          </DField>
          <DField label="Gender" name="gender">
            <select name="gender" defaultValue="" className={controlClass(false)}>
              <option value="">Not specified</option>
              <option value="Female">Female</option>
              <option value="Male">Male</option>
            </select>
          </DField>
          <DField label="District (optional)" name="district" error={errors.district}>
            <input
              type="text"
              name="district"
              maxLength={120}
              autoComplete="address-level2"
              placeholder="Hargeisa"
              defaultValue={""}
              onBlur={blur("district")}
              className={controlClass(Boolean(errors.district))}
              {...invalidProps("district", errors.district)}
            />
          </DField>
          <DField label="Home address (optional)" name="address" error={errors.address} full>
            <input
              type="text"
              name="address"
              maxLength={500}
              autoComplete="street-address"
              placeholder="Street or neighbourhood"
              defaultValue={""}
              onBlur={blur("address")}
              className={controlClass(Boolean(errors.address))}
              {...invalidProps("address", errors.address)}
            />
          </DField>
          <DField label="Student photo (optional)" name="profileImageRef" full>
            <StudentPhotoField mode="new" hiddenFieldName="profileImageRef" />
          </DField>
        </FieldGrid>

        <div className="mt-6 border-t border-border pt-5">
          <div className="mb-3">
            <div className="text-sm font-semibold text-ink">Enroll now (optional)</div>
            <p className="text-[13px] text-muted">
              Pick a batch and the courses the student takes in it to enroll them straight away. Each course gets its
              own fee schedule. You can also do this later from Admissions or the student&apos;s page.
            </p>
          </div>
          <FieldGrid>
            <DField label="Batch" name="batchId" full>
              <select
                name="batchId"
                value={batchId}
                onChange={(event) => {
                  setBatchId(event.target.value);
                  const next = enrollBatches.find((batch) => batch.id === event.target.value);
                  setCourseIds(next && next.courses.length === 1 ? [next.courses[0].id] : []);
                }}
                className={controlClass(false)}
              >
                <option value="">Don&apos;t enroll yet</option>
                {enrollBatches.map((batch) => (
                  <option key={batch.id} value={batch.id}>
                    {batch.code} · {batch.courses.map((course) => course.name).join(" + ")} · {batch.branchName}
                  </option>
                ))}
              </select>
            </DField>
            {enrollBatch && (
              <div className="col-span-full flex min-w-0 flex-col gap-1.5">
                <span id="reg-courses-label" className="text-[13px] font-semibold text-ink">
                  Courses to take (pick one or more)
                  <span aria-hidden="true" className="text-[#B91C1C]">
                    {" "}
                    *
                  </span>
                </span>
                <div role="group" aria-labelledby="reg-courses-label" className="flex flex-wrap gap-2">
                  {enrollBatch.courses.map((course) => {
                    const on = courseIds.includes(course.id);
                    return (
                      <label
                        key={course.id}
                        className={`relative inline-flex min-h-11 cursor-pointer items-center rounded-full border px-3.5 text-sm font-semibold transition-colors duration-150 has-[:focus-visible]:ring-2 has-[:focus-visible]:ring-brand/30 ${
                          on ? "border-brand bg-brand text-white" : "border-border-strong bg-surface text-ink hover:bg-app"
                        }`}
                      >
                        <input
                          type="checkbox"
                          name="courseIds"
                          value={course.id}
                          checked={on}
                          onChange={() =>
                            setCourseIds((current) =>
                              current.includes(course.id) ? current.filter((id) => id !== course.id) : [...current, course.id],
                            )
                          }
                          className="sr-only"
                          {...(errors.courseIds && courseIds.length === 0 ? invalidProps("courseIds", errors.courseIds) : {})}
                        />
                        {course.name}
                      </label>
                    );
                  })}
                </div>
                {errors.courseIds && (
                  <span id="fe-courseIds" role="alert" className="text-xs font-medium text-[#B91C1C]">
                    {errors.courseIds}
                  </span>
                )}
              </div>
            )}
            {batchId && (
              <>
                <PaymentPlanField name="paymentPlanIntervalMonths" defaultValue={1} />
                <DField label="Total fee per course (USD)" name="paymentPlanAmountDollars" required error={errors.paymentPlanAmountDollars}>
                  <input
                    type="text"
                    inputMode="decimal"
                    name="paymentPlanAmountDollars"
                    placeholder="0.00"
                    onBlur={blur("paymentPlanAmountDollars")}
                    className={controlClass(Boolean(errors.paymentPlanAmountDollars))}
                    {...invalidProps("paymentPlanAmountDollars", errors.paymentPlanAmountDollars)}
                  />
                </DField>
              </>
            )}
          </FieldGrid>
        </div>

        <FormErrorBanner message={banner} />
      </DialogBody>
      <DialogFooter onCancel={onCancel} submitLabel="Register student" pendingLabel="Registering…" pending={pending} />
    </form>
  );
}

const TITLE = "Register student";
const SUBTITLE = "A student number like STD-000123 is created automatically.";

/** Header action on Students: opens the registration dialog. Also opened by
 * `/academy/students?register=1` (the empty list's link, and the old
 * /academy/students/new address, which redirects there). */
export function RegisterStudentButton({ openedByUrl = false, ...props }: RegisterStudentOptions & { openedByUrl?: boolean }) {
  const [open, setOpen] = useUrlOpenedDialog(openedByUrl);
  return (
    <>
      <button
        type="button"
        onClick={() => setOpen(true)}
        className="inline-flex h-11 items-center rounded-lg bg-brand px-4 font-semibold text-white transition-colors duration-150 hover:bg-brand-hover"
      >
        Register student
      </button>
      <DesignDialog open={open} onOpenChange={setOpen} title={TITLE} description={SUBTITLE}>
        {open && <RegisterStudentFields {...props} onCancel={() => setOpen(false)} />}
      </DesignDialog>
    </>
  );
}
