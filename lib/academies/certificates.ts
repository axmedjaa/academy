/**
 * PLAN.md Phase 5, Item 57 — `issueCertificate(studentId, batchId,
 * courseId)`. Certificate Lifecycle table: `Eligible -> Issued`, actor
 * Owner/Admin/Manager (`canManage`'s "full"-or-"manage" gate), blocked by
 * the `(student_id, batch_id, course_id)` unique constraint — see this
 * file's module comment for the full retry-loop shape. `courseId` must be
 * one of the batch's courses; it may be omitted only when the batch runs
 * exactly one course (that course is used, as before multi-course batches).
 */
/**
 * Accepts either the student's UUID `id` OR their human-readable
 * `studentNumber` (e.g. "STD-000001") — app/academy/students/students-list.tsx's
 * "Student #" column is the only identifier that page actually displays for
 * copy/paste, same gap fixed for lib/academies/id-cards.ts's
 * resolveScopedStudent (see that function's own doc comment for the full
 * reasoning). `(academy_id, student_number)` is a DB-level unique
 * constraint, so this is still an exact match, not a fuzzy search.
 */
async function resolveStudentIdOrNumber(
  executor: DbClient,
  academyId: string,
  studentIdOrNumber: string,
): Promise<string | null> {
  const trimmed = studentIdOrNumber.trim();
  if (trimmed.length === 0) return null;
  const isUuid = z.string().uuid().safeParse(trimmed).success;

  const [row] = await executor
    .select({ id: students.id })
    .from(students)
    .where(
      and(
        eq(students.academyId, academyId),
        isUuid ? eq(students.id, trimmed) : ilike(students.studentNumber, trimmed),
      ),
    )
    .limit(1);
  return row?.id ?? null;
}

/**
 * Same idea as resolveStudentIdOrNumber above, for batches' own
 * human-readable identifier: `code` (e.g. "batch3"), unique per
 * `(academy_id, code)`.
 */
async function resolveBatchIdOrCode(
  executor: DbClient,
  academyId: string,
  batchIdOrCode: string,
): Promise<string | null> {
  const trimmed = batchIdOrCode.trim();
  if (trimmed.length === 0) return null;
  const isUuid = z.string().uuid().safeParse(trimmed).success;

  const [row] = await executor
    .select({ id: batches.id })
    .from(batches)
    .where(
      and(
        eq(batches.academyId, academyId),
        isUuid ? eq(batches.id, trimmed) : ilike(batches.code, trimmed),
      ),
    )
    .limit(1);
  return row?.id ?? null;
}

/** The batch's course to certify: the given one if it belongs to the batch
 * (same academy), or the only course when none is given. */
async function resolveBatchCourse(
  executor: DbClient,
  academyId: string,
  batchId: string,
  courseId: string | undefined,
): Promise<{ ok: true; courseId: string } | { ok: false; error: CertificateActionError }> {
  const rows = await executor
    .select({ courseId: batchCourses.courseId })
    .from(batchCourses)
    .where(and(eq(batchCourses.academyId, academyId), eq(batchCourses.batchId, batchId)));
  const wanted = courseId?.trim();
  if (wanted) {
    if (!z.string().uuid().safeParse(wanted).success || !rows.some((row) => row.courseId === wanted)) {
      return { ok: false, error: COURSE_NOT_IN_BATCH };
    }
    return { ok: true, courseId: wanted };
  }
  if (rows.length === 1) return { ok: true, courseId: rows[0].courseId };
  return { ok: false, error: rows.length === 0 ? COURSE_NOT_IN_BATCH : COURSE_REQUIRED };
}

export async function issueCertificate(
  actorContext: AuthContext,
  studentIdOrNumber: string,
  batchIdOrCode: string,
  courseIdInput?: string,
): Promise<IssueCertificateResult> {
  const resolved = await resolveCertificatesAccess(actorContext);
  if (!resolved.ok) return resolved;
  const { academyId, membershipRole, permissionLevel } = resolved.access;

  if (!canManage(permissionLevel)) {
    return { ok: false, error: FORBIDDEN };
  }

  const studentId = await resolveStudentIdOrNumber(db, academyId, studentIdOrNumber);
  if (!studentId) {
    return { ok: false, error: STUDENT_NOT_FOUND };
  }

  const batchId = await resolveBatchIdOrCode(db, academyId, batchIdOrCode);
  if (!batchId || !(await isBatchInScope(resolved.access.scope, academyId, batchId))) {
    return { ok: false, error: BATCH_NOT_FOUND };
  }

  const course = await resolveBatchCourse(db, academyId, batchId, courseIdInput);
  if (!course.ok) {
    return { ok: false, error: course.error };
  }
  const courseId = course.courseId;

  const withCourseColumn = await hasCertificateCourseColumn();
  if (!withCourseColumn) {
    // Before 0035 a certificate's course is the batch's primary course and
    // the old one-per-batch rule applies: only single-course batches.
    const [batchRow] = await db.select({ courseId: batches.courseId }).from(batches).where(eq(batches.id, batchId)).limit(1);
    const batchCourseRows = await db
      .select({ courseId: batchCourses.courseId })
      .from(batchCourses)
      .where(and(eq(batchCourses.academyId, academyId), eq(batchCourses.batchId, batchId)));
    if (batchCourseRows.length > 1 || batchRow?.courseId !== courseId) {
      return { ok: false, error: COURSE_CERTIFICATES_NOT_ENABLED };
    }
  }

  const eligible = await isStudentEligibleForCertificate(db, academyId, studentId, batchId, courseId);
  if (!eligible) {
    return { ok: false, error: NOT_ELIGIBLE };
  }

  for (let attempt = 0; attempt < MAX_INSERT_ATTEMPTS; attempt += 1) {
    try {
      const result = await db.transaction(async (tx) => {
        const [existing] = await tx
          .select({ id: certificates.id })
          .from(certificates)
          .where(
            and(
              eq(certificates.studentId, studentId),
              eq(certificates.batchId, batchId),
              withCourseColumn ? eq(certificates.courseId, courseId) : undefined,
            ),
          )
          .limit(1);
        if (existing) {
          return { kind: "duplicate" as const };
        }

        const certificateCode = generateCertificateCode();

        let row: typeof certificates.$inferSelect;
        if (withCourseColumn) {
          [row] = await tx
            .insert(certificates)
            .values({
              academyId,
              studentId,
              batchId,
              courseId,
              certificateCode,
              issuedBy: actorContext.userId,
            })
            .returning();
        } else {
          // Pre-0035 insert: the column list must not name course_id.
          const inserted = await tx.execute<{ id: string }>(
            sql`insert into ${certificates} (academy_id, student_id, batch_id, certificate_code, issued_by)
                values (${academyId}, ${studentId}, ${batchId}, ${certificateCode}, ${actorContext.userId})
                returning id`,
          );
          [row] = await selectCertificateRows(tx, eq(certificates.id, inserted.rows[0].id), 1);
        }

        await recordAudit(
          {
            actorUserId: actorContext.userId,
            actorRole: membershipRole,
            academyId,
            action: "issueCertificate",
            entityType: "certificate",
            entityId: row.id,
            after: toCertificateRecord(row),
          },
          tx,
        );

        return { kind: "ok" as const, row };
      });

      if (result.kind === "duplicate") {
        return { ok: false, error: DUPLICATE_CERTIFICATE };
      }

      // Item 58b — `certificate.issued` notification. Recipient: the
      // issuing actor (`actorContext.userId`). Called with the default `db`
      // client, after this attempt's transaction has already committed
      // (only reached once `result.kind === "ok"`) — see
      // lib/academies/approval-requests.ts's module comment ("Why
      // enqueueNotification is called with the default db client") for why
      // a notification failure must never affect the already-committed
      // business outcome.
      try {
        await enqueueNotification({
          eventType: "certificate.issued",
          entityId: result.row.id,
          templateId: "certificate.issued",
          academyId,
          userId: actorContext.userId,
        });
      } catch (err) {
        logger.error("Failed to enqueue certificate.issued notification", {
          certificateId: result.row.id,
          academyId,
          error: err instanceof Error ? err.message : String(err),
        });
      }

      return { ok: true, certificate: toCertificateRecord(result.row) };
    } catch (err) {
      if (isUniqueViolation(err)) {
        continue; // fresh transaction, fresh code candidate, next attempt
      }
      throw err;
    }
  }

  throw new Error(
    "issueCertificate: exhausted retry attempts generating a unique certificate code.",
  );
}

export type CancelCertificateResult =
  | { ok: true; certificate: CertificateRecord }
  | { ok: false; error: CertificateActionError };

/**
 * PLAN.md Phase 5, Item 57 — `cancelCertificate`. Certificate Lifecycle
 * table: `Issued -> Cancelled`, "reason required", same Owner/Admin/Manager
 * gate as `issueCertificate`. Non-destructive: the row is never deleted,
 * only `status`/`cancelled_at`/`cancelled_by`/`cancellation_reason` are set
 * — it stays permanently visible on `/verify/[certificateCode]` afterward,
 * showing "cancelled" (DESIGN.md's Archive & Deactivation Rules table:
 * "Certificates | Owner/Admin/Manager (`cancelled` status) | ... | yes,
 * permanently (public verification) | ... | no (cancellation is
 * terminal)"). Cancelling an already-cancelled certificate is refused with
 * `already_cancelled` — the lifecycle table's own "(terminal)" row: "a
 * cancelled certificate is never re-activated."
 */
export async function cancelCertificate(
  actorContext: AuthContext,
  certificateId: string,
  reason: string,
): Promise<CancelCertificateResult> {
  const resolved = await resolveCertificatesAccess(actorContext);
  if (!resolved.ok) return resolved;
  const { academyId, membershipRole, permissionLevel } = resolved.access;

  if (!canManage(permissionLevel)) {
    return { ok: false, error: FORBIDDEN };
  }

  const parsedId = z.string().uuid().safeParse(certificateId);
  if (!parsedId.success) {
    return { ok: false, error: CERTIFICATE_NOT_FOUND };
  }

  const parsedReason = cancelCertificateReasonSchema.safeParse(reason);
  if (!parsedReason.success) {
    return {
      ok: false,
      error: {
        code: "validation",
        message: parsedReason.error.issues[0]?.message ?? "A cancellation reason is required.",
      },
    };
  }

  const result = await db.transaction(async (tx) => {
    const [certificate] = await tx
      .select(certificateColumnsWithoutCourse)
      .from(certificates)
      .where(and(eq(certificates.id, certificateId), eq(certificates.academyId, academyId)))
      .for("update");
    if (!certificate || !(await isBatchInScope(resolved.access.scope, academyId, certificate.batchId, tx))) {
      return { kind: "not_found" as const };
    }
    if (certificate.status === "cancelled") {
      return { kind: "already_cancelled" as const };
    }

    const [updated] = await tx
      .update(certificates)
      .set({
        status: "cancelled",
        cancelledAt: new Date(),
        cancelledBy: actorContext.userId,
        cancellationReason: parsedReason.data,
      })
      .where(eq(certificates.id, certificateId))
      .returning(certificateColumnsWithoutCourse);

    await recordAudit(
      {
        actorUserId: actorContext.userId,
        actorRole: membershipRole,
        academyId,
        action: "cancelCertificate",
        entityType: "certificate",
        entityId: certificateId,
        before: { status: certificate.status },
        after: {
          status: updated.status,
          cancelledAt: updated.cancelledAt,
          cancelledBy: updated.cancelledBy,
          cancellationReason: updated.cancellationReason,
        },
      },
      tx,
    );

    // The full record (with its course, read the way this database stores it).
    const [row] = await selectCertificateRows(tx, eq(certificates.id, updated.id), 1);
    return { kind: "ok" as const, row };
  });

  if (result.kind === "not_found") {
    return { ok: false, error: CERTIFICATE_NOT_FOUND };
  }
  if (result.kind === "already_cancelled") {
    return { ok: false, error: ALREADY_CANCELLED };
  }

  // Item 58b — `certificate.cancelled` notification. Recipient: the
  // cancelling actor (`actorContext.userId`). Called with the default `db`
  // client, after `cancelCertificate`'s own transaction has already
  // committed (only reached once `result.kind === "ok"`) — same "why db,
  // not tx" reasoning as `issueCertificate` above and
  // lib/academies/approval-requests.ts's module comment.
  try {
    await enqueueNotification({
      eventType: "certificate.cancelled",
      entityId: result.row.id,
      templateId: "certificate.cancelled",
      academyId,
      userId: actorContext.userId,
    });
  } catch (err) {
    logger.error("Failed to enqueue certificate.cancelled notification", {
      certificateId: result.row.id,
      academyId,
      error: err instanceof Error ? err.message : String(err),
    });
  }

  return { ok: true, certificate: toCertificateRecord(result.row) };
}

