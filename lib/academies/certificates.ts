/**
 * PLAN.md Phase 5, Item 57 — "`issueCertificate` (eligibility: published
 * Pass result required in that batch)/`cancelCertificate`
 * (`/academy/certificates`)." Item 62's public `verifyCertificate` lives
 * here too (rather than a separate file) — it shares the same
 * `certificates`/`certificate_verifications` tables and this is the only
 * place either is touched.
 *
 * ---------------------------------------------------------------------
 * Permission gating
 * ---------------------------------------------------------------------
 * lib/auth/academy-permissions.ts's `ACADEMY_CERTIFICATES_ACTION` row (see
 * its own module comment): Owner="full", Admin/Manager="manage",
 * Trainer="view", Admissions Officer/Finance Officer=no entry ("none").
 * `canManage`'s "full"-or-"manage" gate below is the ONLY gate
 * `issueCertificate`/`cancelCertificate` use — Trainer's "view" passes
 * neither (list/read-only), matching PLAN.md's Master Permission Matrix
 * "Certificates (issue/cancel)" row exactly (Full/Manage/Manage/—/—/View).
 *
 * ---------------------------------------------------------------------
 * Eligibility — reuses Phase 3's exact pass/fail machinery, nothing new
 * ---------------------------------------------------------------------
 * PLAN.md Phase 5: "`issueCertificate(studentId, batchId)` is server-side
 * blocked unless the given student has at least one `exam_results` row for
 * that `batch_id` with `status = published` and a `Pass` outcome under the
 * `grade_bands` active at the time that result was published (the same
 * `grade_configuration_id` snapshot already stored on the result, per Phase
 * 3)." Rather than trusting the `pass_fail` column a published row already
 * carries (set once, at publish time, by `publishResults` — see
 * lib/academies/results.ts's own comment on why that column is immutable
 * thereafter), `isStudentEligibleForCertificate` below re-derives the
 * outcome from scratch: it loads the exact `grade_bands` for the row's own
 * snapshotted `grade_configuration_id` and re-evaluates `marks_obtained`
 * against them with `evaluateGradeBand` — the same function
 * `publishResults` itself calls (imported, not reimplemented, per this
 * item's own instruction to "reuse that exact logic rather than
 * reinventing it"). This is belt-and-braces rather than strictly
 * necessary (a published row's `pass_fail` should already agree), but it
 * is what PLAN.md's own wording ("re-derive... using the same
 * grade_configuration_id snapshot") literally asks for, and it means
 * certificate eligibility never silently drifts from the grade-bands
 * mechanism even if that invariant were ever violated elsewhere.
 *
 * Certificates are per course: a student gets one certificate per course
 * they complete, also when a batch runs several courses. Eligibility is
 * therefore checked per (student, batch, course): any ONE published Pass
 * result in an exam of that course in that batch is sufficient — the plan
 * defines no "final exam" concept, so each exam of the course independently
 * satisfies eligibility. A pass in another course of the same batch never
 * counts.
 *
 * ---------------------------------------------------------------------
 * Certificate code — opaque, non-sequential, collision-retried
 * ---------------------------------------------------------------------
 * Generated by `generateCertificateCode` (cryptographically random, drawn
 * from `randomBytes`, never a counter/sequence) and inserted inside the
 * same "fresh transaction per retry attempt" loop as
 * lib/academies/student-payments.ts's `issueReceipt`/`generateReceiptNumber`
 * — see that function's own module comment for why a caught unique
 * violation can't simply be retried inside the same (now-aborted)
 * transaction. Unlike `issueReceipt`, this loop also re-checks the
 * `(student_id, batch_id)` unique constraint explicitly at the top of every
 * attempt (`existing` lookup below) so a genuine duplicate-certificate
 * race collapses into the clean `DUPLICATE_CERTIFICATE` error on its very
 * next attempt rather than exhausting all retries — a caught unique
 * violation from the DB (via `isUniqueViolation`, same helper shape as
 * every other file in this codebase) is still the fallback path for the
 * rarer `certificate_code` collision case, per this item's own brief.
 *
 * ---------------------------------------------------------------------
 * `verifyCertificate` — intentionally NOT tenant-scoped
 * ---------------------------------------------------------------------
 * Every other lookup in this codebase resolves the caller's own academyId
 * first and scopes every query to it. This one deliberately does not:
 * PLAN.md's `/verify/[certificateCode]` is public and unauthenticated, a
 * certificate code is the sole lookup key, and the route "works unchanged
 * for closed academies" (PLAN.md Phase 5, restated in DESIGN.md §10 as a
 * "deliberate, tested distinction: closure affects the academy's own
 * console, never the public verification surface"). So this function never
 * joins against `academies`/`academy_subscriptions` at all, and a
 * suspended/closed academy's certificates verify identically to any other
 * academy's. A nonexistent code and a would-be cross-academy confusion are
 * both impossible to distinguish from the response shape (there is no
 * "wrong academy" case — the code alone determines the result), satisfying
 * the same IDOR-safe generic-response convention used everywhere else in
 * this codebase.
 *
 * A verification attempt against a code that resolves to a real
 * certificate writes a `certificate_verifications` row (audit trail per
 * PLAN.md: "verification rate-limited and logged"). An attempt against a
 * code that does NOT resolve writes nothing — logging failed lookups would
 * itself become an enumeration side channel (an attacker could infer
 * real-vs-fake codes by, e.g., timing or by later reading their own traffic
 * reflected in some future admin view of failed-verification volume);
 * PLAN.md never explicitly states this either way, so this is a documented
 * judgment call in favor of the narrower, safer logging scope.
 */
function canManage(level: AcademyPermissionLevel): boolean {
  return level === "full" || level === "manage";
}

