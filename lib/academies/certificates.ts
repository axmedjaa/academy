export interface PublicCertificateVerification {
  studentName: string;
  programName: string;
  issuedAt: Date;
  status: "valid" | "cancelled";
}

export interface VerifyCertificateError {
  code: "not_found" | "rate_limited";
  message: string;
}

export type VerifyCertificateResult =
  | { ok: true; certificate: PublicCertificateVerification }
  | { ok: false; error: VerifyCertificateError };

// Deliberately generic and identical for every failure mode (malformed
// code, well-formed-but-nonexistent code, cancelled-but-real code is NOT
// this — a cancelled certificate is `ok: true` with status "cancelled",
// per PLAN.md: "the verification endpoint's only 'not found' case is a
// genuinely nonexistent code, never a cancelled one").
const VERIFY_NOT_FOUND: VerifyCertificateError = {
  code: "not_found",
  message: "No certificate was found for this code.",
};

// Deliberately its own distinct code/message from VERIFY_NOT_FOUND — per
// this item's brief, a rate-limited response and a genuine not-found are
// not required to look identical to each other (only real-vs-fake codes
// must be indistinguishable, since a rate-limit response never depends on
// whether the submitted code happens to be real). Still generic: it never
// hints at whether *this* IP's history includes a real or fake code.
const VERIFY_RATE_LIMITED: VerifyCertificateError = {
  code: "rate_limited",
  message: "Too many verification attempts. Please try again later.",
};

const certificateCodeInputSchema = z.string().trim().min(1).max(64);

/**
 * PLAN.md Phase 5, Item 62 — public `verifyCertificate(certificateCode,
 * ip)`. See this file's module comment ("`verifyCertificate` — intentionally
 * NOT tenant-scoped") for the full reasoning on cross-academy lookup,
 * closed-academy behavior, and the choice not to log failed lookups.
 *
 * Returns ONLY the four public-safe fields PLAN.md/DESIGN.md name — student
 * name, program name, issue date, status — never any internal id
 * (certificate/student/batch/academy/user), never any other student field
 * (email/phone/address/etc.), and never any academy-level detail.
 *
 * Rate-limited per IP via lib/academies/certificate-verify-rate-limit.ts's
 * `checkCertificateVerifyRateLimit` (PLAN.md: "verification rate-limited and
 * logged") — checked before any DB work, same convention as `signIn`'s own
 * rate-limit check. A rate-limited call returns the distinct `rate_limited`
 * error rather than `not_found`; see `VERIFY_RATE_LIMITED`'s own comment for
 * why that distinction is safe to expose.
 */
export async function verifyCertificate(
  certificateCode: string,
  ip: string,
  userAgent?: string,
): Promise<VerifyCertificateResult> {
  // Checked (and incremented) before any parsing/DB work — same convention
  // as signIn's own rate-limit check in lib/auth/actions.ts — so a flood of
  // requests against this public, unauthenticated endpoint is rejected
  // cheaply regardless of whether the submitted code is even well-formed.
  const rateLimit = await checkCertificateVerifyRateLimit(ip);
  if (!rateLimit.allowed) {
    return { ok: false, error: VERIFY_RATE_LIMITED };
  }

  const parsedCode = certificateCodeInputSchema.safeParse(certificateCode);
  if (!parsedCode.success) {
    return { ok: false, error: VERIFY_NOT_FOUND };
  }

  const [row] = await db
    .select({
      id: certificates.id,
      status: certificates.status,
      issuedAt: certificates.issuedAt,
      studentFullName: students.fullName,
      programName: programs.name,
    })
    .from(certificates)
    .innerJoin(students, eq(certificates.studentId, students.id))
    .innerJoin(batches, eq(certificates.batchId, batches.id))
    .innerJoin(courses, eq(batches.courseId, courses.id))
    .innerJoin(programs, eq(courses.programId, programs.id))
    .where(eq(certificates.certificateCode, parsedCode.data))
    .limit(1);

  if (!row) {
    return { ok: false, error: VERIFY_NOT_FOUND };
  }

  // Logged only for a code that resolves to a real certificate — see this
  // file's module comment on why a failed lookup is never logged.
  await db.insert(certificateVerifications).values({
    certificateId: row.id,
    ip,
    userAgent,
  });

  return {
    ok: true,
    certificate: {
      studentName: row.studentFullName,
      programName: row.programName,
      issuedAt: row.issuedAt,
      status: row.status === "cancelled" ? "cancelled" : "valid",
    },
  };
}
