interface ResolvedCertificatesAccess {
  academyId: string;
  membershipRole: AcademyRole;
  permissionLevel: AcademyPermissionLevel;
}

type ResolveCertificatesAccessResult =
  | { ok: true; access: ResolvedCertificatesAccess }
  | { ok: false; error: CertificateActionError };

async function resolveCertificatesAccess(
  actorContext: AuthContext,
): Promise<ResolveCertificatesAccessResult> {
  const access = await checkAcademyAccessForContext(actorContext);
  if (access.level === "blocked") {
    return { ok: false, error: { code: "blocked", message: access.message } };
  }

  const permissionLevel = getAcademyPermissionLevel(
    access.membershipRole,
    ACADEMY_CERTIFICATES_ACTION,
  );
  if (permissionLevel === "none") {
    return { ok: false, error: FORBIDDEN };
  }

  return {
    ok: true,
    access: {
      academyId: access.academyId,
      membershipRole: access.membershipRole,
      permissionLevel,
    },
  };
}

interface EligibilityGradeBand {
  label: string;
  minMark: number;
  maxMark: number;
  isPass: boolean;
}

/**
 * See this file's module comment ("Eligibility") for the full derivation.
 * Loads every published `exam_results` row for this exact
 * (academy, student, batch) triple, and re-evaluates each one's own
 * snapshotted `grade_configuration_id` bands against its `marks_obtained`
 * — any single Pass is sufficient.
 */
async function isStudentEligibleForCertificate(
  executor: DbClient,
  academyId: string,
  studentId: string,
  batchId: string,
): Promise<boolean> {
  const rows = await executor
    .select({
      marksObtained: examResults.marksObtained,
      gradeConfigurationId: examResults.gradeConfigurationId,
    })
    .from(examResults)
    .where(
      and(
        eq(examResults.academyId, academyId),
        eq(examResults.studentId, studentId),
        eq(examResults.batchId, batchId),
        eq(examResults.status, "published"),
      ),
    );

  if (rows.length === 0) return false;

  const bandsByConfig = new Map<string, EligibilityGradeBand[]>();

  for (const row of rows) {
    if (row.marksObtained === null) continue; // Defensive — publishResults never leaves this null.

    let bands = bandsByConfig.get(row.gradeConfigurationId);
    if (!bands) {
      const bandRows = await executor
        .select()
        .from(gradeBands)
        .where(eq(gradeBands.gradeConfigurationId, row.gradeConfigurationId));
      bands = bandRows.map((band) => ({
        label: band.label,
        minMark: Number(band.minMark),
        maxMark: Number(band.maxMark),
        isPass: band.isPass,
      }));
      bandsByConfig.set(row.gradeConfigurationId, bands);
    }

    const band = evaluateGradeBand(Number(row.marksObtained), bands);
    if (band?.isPass) return true;
  }

  return false;
}

const CERTIFICATE_CODE_ALPHABET = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789"; // Crockford-style, no 0/O/1/I ambiguity.
const CERTIFICATE_CODE_GROUP_LENGTH = 4;
const CERTIFICATE_CODE_GROUPS = 4; // 16 random characters total, grouped for readability.

/**
 * Opaque, non-sequential, cryptographically random certificate code (never
 * a counter/sequence — see this file's module comment). 16 characters drawn
 * from a 32-symbol alphabet is ~80 bits of entropy, grouped into
 * hyphen-separated 4-character blocks (e.g. "AB3D-7HKL-9MNP-Q2ST") purely
 * for human readability on a printed/PDF certificate — the grouping carries
 * no meaning and is not parsed back apart anywhere.
 */
function generateCertificateCode(): string {
  const totalChars = CERTIFICATE_CODE_GROUP_LENGTH * CERTIFICATE_CODE_GROUPS;
  const bytes = randomBytes(totalChars);
  let chars = "";
  for (let i = 0; i < totalChars; i += 1) {
    chars += CERTIFICATE_CODE_ALPHABET[bytes[i] % CERTIFICATE_CODE_ALPHABET.length];
  }
  const groups: string[] = [];
  for (let i = 0; i < CERTIFICATE_CODE_GROUPS; i += 1) {
    groups.push(chars.slice(i * CERTIFICATE_CODE_GROUP_LENGTH, (i + 1) * CERTIFICATE_CODE_GROUP_LENGTH));
  }
  return groups.join("-");
}

// Generous on purpose, same reasoning as student-payments.ts's
// MAX_INSERT_ATTEMPTS: each attempt is a full fresh transaction, so erring
// high costs little against the astronomically low real collision odds.
const MAX_INSERT_ATTEMPTS = 20;

export type ListCertificatesResult =
  | { ok: true; certificates: CertificateRecord[]; canManage: boolean }
  | { ok: false; error: CertificateActionError };

/** Academy-scoped read, optionally narrowed to one student and/or batch.
 * Available to every non-"none" permission level (including Trainer's
 * "view") — support for a later, separate item's `/academy/certificates`
 * UI is out of scope for this wave, but the read path itself is needed now
 * so that UI has something to call. */
export async function listCertificates(
  actorContext: AuthContext,
  filters: { studentId?: string; batchId?: string } = {},
): Promise<ListCertificatesResult> {
  const resolved = await resolveCertificatesAccess(actorContext);
  if (!resolved.ok) return resolved;
  const { academyId, permissionLevel } = resolved.access;

  const conditions = [eq(certificates.academyId, academyId)];
  if (filters.studentId) {
    conditions.push(eq(certificates.studentId, filters.studentId));
  }
  if (filters.batchId) {
    conditions.push(eq(certificates.batchId, filters.batchId));
  }

  const rows = await db
    .select()
    .from(certificates)
    .where(and(...conditions));

  return {
    ok: true,
    certificates: rows.map(toCertificateRecord),
    canManage: canManage(permissionLevel),
  };
}

export type GetCertificateResult =
  | { ok: true; certificate: CertificateRecord }
  | { ok: false; error: CertificateActionError };

/** Tenant-scoped single read. IDOR-safe: nonexistent or cross-academy id
 * both return the identical generic `not_found` — same convention as
 * lib/academies/student-payments.ts's `getReceipt`. This is the
 * *internal, authenticated* lookup (DESIGN.md §9.7's "Certificate
 * Verification (internal lookup)" row); the public unauthenticated lookup
 * is `verifyCertificate`, further down this file. */
export async function getCertificate(
  actorContext: AuthContext,
  certificateId: string,
): Promise<GetCertificateResult> {
  const resolved = await resolveCertificatesAccess(actorContext);
  if (!resolved.ok) return resolved;
  const { academyId } = resolved.access;

  const parsedId = z.string().uuid().safeParse(certificateId);
  if (!parsedId.success) {
    return { ok: false, error: CERTIFICATE_NOT_FOUND };
  }

  const [row] = await db
    .select()
    .from(certificates)
    .where(and(eq(certificates.id, certificateId), eq(certificates.academyId, academyId)))
    .limit(1);
  if (!row) {
    return { ok: false, error: CERTIFICATE_NOT_FOUND };
  }

  return { ok: true, certificate: toCertificateRecord(row) };
}

export type IssueCertificateResult =
  | { ok: true; certificate: CertificateRecord }
  | { ok: false; error: CertificateActionError };

/**
 * PLAN.md Phase 5, Item 57 — `issueCertificate(studentId, batchId)`.
 * Certificate Lifecycle table: `Eligible -> Issued`, actor Owner/Admin/
 * Manager (`canManage`'s "full"-or-"manage" gate), "blocked by the
 * `(student_id, batch_id)` unique constraint" — see this file's module
 * comment for the full retry-loop shape.
 */
export async function issueCertificate(
  actorContext: AuthContext,
  studentId: string,
  batchId: string,
): Promise<IssueCertificateResult> {
  const resolved = await resolveCertificatesAccess(actorContext);
  if (!resolved.ok) return resolved;
  const { academyId, membershipRole, permissionLevel } = resolved.access;

  if (!canManage(permissionLevel)) {
    return { ok: false, error: FORBIDDEN };
  }

  const parsedStudentId = z.string().uuid().safeParse(studentId);
  if (!parsedStudentId.success) {
    return { ok: false, error: STUDENT_NOT_FOUND };
  }
  const parsedBatchId = z.string().uuid().safeParse(batchId);
  if (!parsedBatchId.success) {
    return { ok: false, error: BATCH_NOT_FOUND };
  }

  const [student] = await db
    .select({ id: students.id, academyId: students.academyId })
    .from(students)
    .where(eq(students.id, studentId))
    .limit(1);
  if (!student || student.academyId !== academyId) {
    return { ok: false, error: STUDENT_NOT_FOUND };
  }

  const [batch] = await db
    .select({ id: batches.id, academyId: batches.academyId })
    .from(batches)
    .where(eq(batches.id, batchId))
    .limit(1);
  if (!batch || batch.academyId !== academyId) {
    return { ok: false, error: BATCH_NOT_FOUND };
  }

  const eligible = await isStudentEligibleForCertificate(db, academyId, studentId, batchId);
  if (!eligible) {
    return { ok: false, error: NOT_ELIGIBLE };
  }

  for (let attempt = 0; attempt < MAX_INSERT_ATTEMPTS; attempt += 1) {
    try {
      const result = await db.transaction(async (tx) => {
        const [existing] = await tx
          .select({ id: certificates.id })
          .from(certificates)
          .where(and(eq(certificates.studentId, studentId), eq(certificates.batchId, batchId)))
          .limit(1);
        if (existing) {
          return { kind: "duplicate" as const };
        }

        const certificateCode = generateCertificateCode();

        const [row] = await tx
          .insert(certificates)
          .values({
            academyId,
            studentId,
            batchId,
            certificateCode,
            issuedBy: actorContext.userId,
          })
          .returning();

        await recordAudit(
          {
            actorUserId: actorContext.userId,
            actorRole: membershipRole,
            academyId,
            action: "issueCertificate",
            entityType: "certificate",
            entityId: row.id,
            after: toCertificateRecord(row),
          },
          tx,
        );

        return { kind: "ok" as const, row };
      });

      if (result.kind === "duplicate") {
        return { ok: false, error: DUPLICATE_CERTIFICATE };
      }
      return { ok: true, certificate: toCertificateRecord(result.row) };
    } catch (err) {
      if (isUniqueViolation(err)) {
        continue; // fresh transaction, fresh code candidate, next attempt
      }
      throw err;
    }
  }

  throw new Error(
    "issueCertificate: exhausted retry attempts generating a unique certificate code.",
  );
}

export type CancelCertificateResult =
  | { ok: true; certificate: CertificateRecord }
  | { ok: false; error: CertificateActionError };

/**
 * PLAN.md Phase 5, Item 57 — `cancelCertificate`. Certificate Lifecycle
 * table: `Issued -> Cancelled`, "reason required", same Owner/Admin/Manager
 * gate as `issueCertificate`. Non-destructive: the row is never deleted,
 * only `status`/`cancelled_at`/`cancelled_by`/`cancellation_reason` are set
 * — it stays permanently visible on `/verify/[certificateCode]` afterward,
 * showing "cancelled" (DESIGN.md's Archive & Deactivation Rules table:
 * "Certificates | Owner/Admin/Manager (`cancelled` status) | ... | yes,
 * permanently (public verification) | ... | no (cancellation is
 * terminal)"). Cancelling an already-cancelled certificate is refused with
 * `already_cancelled` — the lifecycle table's own "(terminal)" row: "a
 * cancelled certificate is never re-activated."
 */
export async function cancelCertificate(
  actorContext: AuthContext,
  certificateId: string,
  reason: string,
): Promise<CancelCertificateResult> {
  const resolved = await resolveCertificatesAccess(actorContext);
  if (!resolved.ok) return resolved;
  const { academyId, membershipRole, permissionLevel } = resolved.access;

  if (!canManage(permissionLevel)) {
    return { ok: false, error: FORBIDDEN };
  }

  const parsedId = z.string().uuid().safeParse(certificateId);
  if (!parsedId.success) {
    return { ok: false, error: CERTIFICATE_NOT_FOUND };
  }

  const parsedReason = cancelCertificateReasonSchema.safeParse(reason);
  if (!parsedReason.success) {
    return {
      ok: false,
      error: {
        code: "validation",
        message: parsedReason.error.issues[0]?.message ?? "A cancellation reason is required.",
      },
    };
  }

  const result = await db.transaction(async (tx) => {
    const [certificate] = await tx
      .select()
      .from(certificates)
      .where(and(eq(certificates.id, certificateId), eq(certificates.academyId, academyId)))
      .for("update");
    if (!certificate) {
      return { kind: "not_found" as const };
    }
    if (certificate.status === "cancelled") {
      return { kind: "already_cancelled" as const };
    }

    const [updated] = await tx
      .update(certificates)
      .set({
        status: "cancelled",
        cancelledAt: new Date(),
        cancelledBy: actorContext.userId,
        cancellationReason: parsedReason.data,
      })
      .where(eq(certificates.id, certificateId))
      .returning();

    await recordAudit(
      {
        actorUserId: actorContext.userId,
        actorRole: membershipRole,
        academyId,
        action: "cancelCertificate",
        entityType: "certificate",
        entityId: certificateId,
        before: { status: certificate.status },
        after: {
          status: updated.status,
          cancelledAt: updated.cancelledAt,
          cancelledBy: updated.cancelledBy,
          cancellationReason: updated.cancellationReason,
        },
      },
      tx,
    );

    return { kind: "ok" as const, row: updated };
  });

  if (result.kind === "not_found") {
    return { ok: false, error: CERTIFICATE_NOT_FOUND };
  }
  if (result.kind === "already_cancelled") {
    return { ok: false, error: ALREADY_CANCELLED };
  }
  return { ok: true, certificate: toCertificateRecord(result.row) };
}

