/**
 * This product has no dark mode (see app/globals.css's `color-scheme: light`
 * comment) and no `--popover`/`--accent`/`--destructive`/`--muted-foreground`
 * tokens — shadcn's default generated version of this file references those.
 * Remapped throughout to this app's own `--color-*` tokens (surface/ink/app/
 * border/danger/danger-bg/muted) instead, same convention as
 * components/ui/sonner.tsx; every `dark:` variant removed for the same
 * reason. Structure/behavior otherwise unchanged from the upstream
 * shadcn/Radix component.
 */

function DropdownMenu({
  ...props
}: React.ComponentProps<typeof DropdownMenuPrimitive.Root>) {
  return <DropdownMenuPrimitive.Root data-slot="dropdown-menu" {...props} />
}

